"use strict";
const assert=require("node:assert/strict");
const {createBridgeAuth,digest}=require("../auth");
const master="strong_cloud_run_key_with_43_or_more_chars_2026";
const shared="123456";
const mac=digest(master,shared).toString("hex");
const auth=createBridgeAuth({primaryKey:master,legacyHmac:mac});
assert.equal(auth.hasLegacy,true);
assert.equal(auth.valid(shared),true);
assert.equal(auth.valid(master),true);
assert.equal(auth.valid("000000"),false);
assert.equal(auth.valid("12345"),false);
assert.equal(auth.valid("1234567"),false);
assert.equal(auth.valid(""),false);
assert.equal(auth.valid(null),false);
const initial=1000000;
for(let i=0;i<6;i++)assert.equal(auth.noteFailure("client1",initial),false);
assert.equal(auth.noteFailure("client1",initial),true);
assert.equal(auth.noteFailure("client1",initial+3600001),false);
const disabled=createBridgeAuth({primaryKey:master});
assert.equal(disabled.hasLegacy,false);
assert.equal(disabled.valid(shared),false);
assert.equal(disabled.valid(master),true);
console.log("PASS: master key, six-character HMAC alias, disabled-by-default and failure throttling");
