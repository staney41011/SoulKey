"use strict";
const fs=require("fs"),vm=require("vm"),assert=require("node:assert/strict");
const raw=fs.readFileSync(__dirname+"/NativeAudio.gs","utf8");
const store=new Map();
const p={getProperty:k=>store.get(k),setProperty:(k,v)=>store.set(k,v),deleteProperty:k=>store.delete(k)};
const ctx={PropertiesService:{getScriptProperties:()=>p},SK_AUDIO_LANGUAGES:["en","es"]};
vm.createContext(ctx);
vm.runInContext(raw.slice(raw.indexOf("function skShareModern_("),raw.indexOf("function skAudioReceipt_(")),ctx);
const id="P263-L04",sha="1234567890abcdef123",tag=id+"-en-"+sha.slice(0,16);
const request={tag,sha,review:"approved_english_final",share_epoch:ctx.skShareEpoch_(id,"en")};
const receipt={status:"done",release_tag:tag,source_sha256:sha,mp3_drive_id:"source"};
const proof={status:"copied",tier:"formal",sha,release_tag:tag,review:request.review,source_mp3_id:"source",dest_mp3_id:"dest",dest_filename:"ready.mp3",classroom_folder_id:"folder"};
ctx.skAudioVerifiedSource_=()=>true;
ctx.skPlaybackReceipt_=()=>proof;
ctx.skPlaybackFileValid_=()=>true;
ctx.skPlaybackOwned_=()=>({task:id,lang:"en",tag,sha,review:request.review,tier:"formal",source_mp3_id:"source"});
ctx.DriveApp={getFileById:fid=>fid==="source"?{getName:()=>id+"-en-"+sha.slice(0,16)+".mp3"}:{getId:()=>"dest",getName:()=>"ready.mp3",getUrl:()=>"drive-ready",getSize:()=>10,getParents:()=>({hasNext:()=>true,next:()=>({getId:()=>"folder"})})}};
assert.equal(ctx.skSharePublish_({task:id},"en",receipt,request),true);
ctx.DriveApp={getFileById:()=>{throw Error("website must not access Drive")}};
assert.equal(ctx.skShareRead_(id).total_files,1);
assert.equal(ctx.skShareRead_(id).groups[0].files[0].url,"drive-ready");
ctx.skShareInvalidate_(id);
assert.equal(ctx.skShareRead_(id).total_files,0);
assert.equal(ctx.skSharePublish_({task:id},"en",receipt,request),false);
console.log("CENTRAL_SHARE_INDEX_OK");
